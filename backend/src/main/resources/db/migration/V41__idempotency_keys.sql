-- F3: handing in a test is replay-safe. The browser sends an Idempotency-Key with the submit; the server records the
-- key + a hash of the request and the response it produced, and replays that response for a repeat (a retry after a
-- dropped connection), instead of answering "already handed in". The unique (key, scope) pair makes claiming a key
-- atomic when two copies of the request arrive at once. Old rows are purged nightly (IdempotencyPurger).
CREATE TABLE idempotency_keys (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key  VARCHAR(255) NOT NULL,
    scope            VARCHAR(100) NOT NULL,
    request_hash     VARCHAR(64)  NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    response_status  INT,
    response_body    TEXT,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    completed_at     TIMESTAMPTZ,
    CONSTRAINT uk_idempotency_key_scope UNIQUE (idempotency_key, scope)
);

CREATE INDEX idx_idempotency_keys_created ON idempotency_keys (created_at);
