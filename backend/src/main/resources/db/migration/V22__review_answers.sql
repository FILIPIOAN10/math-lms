-- E4 spaced repetition: the answers a student gives in the daily review. The review queue itself is NOT stored - each
-- question's Leitner box and due date are replayed from the student's multiple-choice answers (practice, handed-in
-- tests and these reviews), like homework progress is derived from attempts. Deleting a question deletes its reviews.
CREATE TABLE review_answers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  BIGINT      NOT NULL REFERENCES users (id),
    item_id     BIGINT      NOT NULL REFERENCES quiz_items (id) ON DELETE CASCADE,
    option_id   BIGINT      REFERENCES quiz_options (id) ON DELETE SET NULL,
    correct     BOOLEAN     NOT NULL,
    answered_at TIMESTAMPTZ NOT NULL
);

-- Today's count, the streak and the replay all read one student's answers in time order.
CREATE INDEX idx_review_answers_student_time ON review_answers (student_id, answered_at);
CREATE INDEX idx_review_answers_item ON review_answers (item_id);
