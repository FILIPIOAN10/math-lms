-- The book's pages written out for reading: each theory photo's text (its transcript, the LaTeX repaired, every figure
-- in place) and the drawings the app made of its figures, so a chapter reads as a lesson instead of a pile of photos.
-- Filled by tutor/scripts/publish_lessons.py; the photos stay the source and go on being shown on demand.
CREATE TABLE en_photo_lessons (
    photo_id   BIGINT PRIMARY KEY REFERENCES en_chapter_photos (id) ON DELETE CASCADE,
    -- Markdown with $LaTeX$; a drawing is a line "![description](desen:<en_photo_drawings.id>)".
    markdown   TEXT        NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- A figure of a page, drawn by the app from exact coordinates (tutor.figures) and compared with the book. Kept in the
-- database, not on disk, so the lessons' backup and the transfer to the server carry them with the text.
CREATE TABLE en_photo_drawings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    photo_id    BIGINT      NOT NULL REFERENCES en_chapter_photos (id) ON DELETE CASCADE,
    number      INT         NOT NULL,
    description TEXT        NOT NULL DEFAULT '',
    png         BYTEA       NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_en_photo_drawings_number UNIQUE (photo_id, number)
);

-- Written by the AI, so a student sees it only once the teacher has read it and shown it, chapter by chapter.
ALTER TABLE en_chapters ADD COLUMN lesson_published BOOLEAN NOT NULL DEFAULT FALSE;
