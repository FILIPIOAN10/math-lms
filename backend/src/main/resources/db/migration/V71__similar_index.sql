-- „Dă-mi una asemănătoare": one embedding per question of the bank (quiz_items) and per worked example of the EN chapter
-- pages (en_chapter_examples), so that after a mistake the student gets the nearest ones by meaning - plain search, no
-- generated text. Derived data, like tutor_chunks: written by the tutor service (tutor.similar_index, from the
-- statements only; no student data), read by the backend with pgvector. Re-running the indexing embeds only what
-- changed (content_hash) or was embedded by another model; a deleted question or example takes its row with it.
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE similar_index (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id       BIGINT       REFERENCES quiz_items (id) ON DELETE CASCADE,
    example_id    BIGINT       REFERENCES en_chapter_examples (id) ON DELETE CASCADE,
    content_hash  CHAR(64)     NOT NULL,
    embedded_with VARCHAR(60)  NOT NULL,
    -- The same size as tutor_chunks.embedding (the tutor's EMBEDDING_DIMENSIONS).
    embedding     vector(1536) NOT NULL,
    CONSTRAINT chk_similar_index_one_source CHECK ((item_id IS NULL) <> (example_id IS NULL))
);

CREATE UNIQUE INDEX ux_similar_index_item ON similar_index (item_id) WHERE item_id IS NOT NULL;
CREATE UNIQUE INDEX ux_similar_index_example ON similar_index (example_id) WHERE example_id IS NOT NULL;
