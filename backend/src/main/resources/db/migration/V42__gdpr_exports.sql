-- GDPR Art. 15 export, built in the background: the ZIP (profile, classes, attempts, comments, photos) can be large,
-- so asking for it queues an outbox event and returns at once; the worker builds the archive here and emails a
-- single-use download link. One live export per account (PENDING or READY); the bytes are dropped after 7 days
-- (the row stays, EXPIRED, as a record that the request was answered).
CREATE TABLE gdpr_exports (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status        VARCHAR(10)  NOT NULL,
    archive       BYTEA,
    requested_at  TIMESTAMPTZ  NOT NULL,
    ready_at      TIMESTAMPTZ,
    expires_at    TIMESTAMPTZ,
    downloaded_at TIMESTAMPTZ,
    CONSTRAINT ck_gdpr_exports_status CHECK (status IN ('PENDING', 'READY', 'EXPIRED'))
);

-- Asking again while one is being built or waiting to be downloaded is answered, never queued twice.
CREATE UNIQUE INDEX uk_gdpr_exports_one_live ON gdpr_exports (user_id) WHERE status IN ('PENDING', 'READY');
CREATE INDEX idx_gdpr_exports_expires ON gdpr_exports (expires_at) WHERE status = 'READY';
