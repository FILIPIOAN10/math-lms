-- F1: an append-only journal of what teachers change ("who changed this grade?", "who deleted the exercise?"), written
-- in the SAME transaction as the change, so a rolled-back change leaves no row and a committed one always has one.
-- Rows hold ids and non-personal text only: `label` is what the row is about at that moment (a class name, a quiz title
-- and question number, an exercise's opening words — teacher-authored content that survives a later delete), `details`
-- what changed ("2 → 4 p"). People are referenced by id and their names are read at display time, so erasing an
-- account (GDPR, the row becomes a pseudonymised tombstone) also anonymises every journal row that names it.
CREATE TABLE admin_audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ  NOT NULL,
    -- Who did it: the teacher, or the newcomer for a join through an invite link. NULL = the account was deleted.
    actor_id    BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    action      VARCHAR(40)  NOT NULL,
    entity_id   BIGINT,
    label       VARCHAR(300) NOT NULL,
    details     VARCHAR(500),
    -- The person the change is about - nearly always a student (a grade, an enrolment); the account itself for an
    -- approval. The per-student filter reads it.
    student_id  BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    -- A second person, when there is one: the parent linked to the student.
    related_user_id BIGINT   REFERENCES users (id) ON DELETE SET NULL
);

-- Newest first, paged by id (keyset): the journal page and every filter read from the top.
CREATE INDEX idx_admin_audit_log_student ON admin_audit_log (student_id, id DESC);
CREATE INDEX idx_admin_audit_log_action ON admin_audit_log (action, id DESC);
CREATE INDEX idx_admin_audit_log_actor ON admin_audit_log (actor_id);
CREATE INDEX idx_admin_audit_log_related_user ON admin_audit_log (related_user_id);
