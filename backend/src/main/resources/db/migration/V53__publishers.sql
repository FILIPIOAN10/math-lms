-- "Edituri": the publishing houses (Art Klett, Intuitext...) whose books a test comes from. None ships with the app:
-- every row is one an administrator added by hand. A test may name one, or none (an official Evaluarea Națională
-- paper belongs to no publisher). Deleting a publisher leaves its tests in place, without a publisher.
CREATE TABLE publishers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120)  NOT NULL,
    description VARCHAR(1000),
    -- The logo's stored file name (FileService key under app.storage.publisher-logos-dir); null = no logo.
    logo_key    VARCHAR(200),
    created_at  TIMESTAMPTZ   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_publishers_name CHECK (btrim(name) <> '')
);

-- One "Art Klett", whatever its case.
CREATE UNIQUE INDEX uq_publishers_name ON publishers (lower(name));

ALTER TABLE quizzes ADD COLUMN publisher_id BIGINT REFERENCES publishers (id) ON DELETE SET NULL;
CREATE INDEX idx_quizzes_publisher ON quizzes (publisher_id);
