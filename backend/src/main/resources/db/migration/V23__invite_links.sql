-- T1 one-step onboarding: stored invite links that carry WHERE the newcomer belongs, so joining needs no admin step.
-- A CLASS link (one per class, many uses) enrols each student who joins; a PARENT link (minted on a student's row, one
-- use) links the parent to that student. Unlike the stateless role invites (signed JWT, still in use), these live in
-- the database so the teacher can cap and revoke them: `uses` is claimed atomically at registration and never passes
-- `max_uses`. Deleting the class or the student removes their links.
CREATE TABLE invite_links (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(64) NOT NULL,
    kind            VARCHAR(10) NOT NULL,
    school_class_id BIGINT      REFERENCES school_classes (id) ON DELETE CASCADE,
    student_id      BIGINT      REFERENCES users (id) ON DELETE CASCADE,
    max_uses        INT         NOT NULL,
    uses            INT         NOT NULL DEFAULT 0,
    expires_at      TIMESTAMPTZ NOT NULL,
    revoked_at      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_invite_links_code UNIQUE (code),
    CONSTRAINT ck_invite_links_kind CHECK (kind IN ('CLASS', 'PARENT')),
    CONSTRAINT ck_invite_links_target CHECK (
        (kind = 'CLASS' AND school_class_id IS NOT NULL AND student_id IS NULL)
        OR (kind = 'PARENT' AND student_id IS NOT NULL AND school_class_id IS NULL)),
    CONSTRAINT ck_invite_links_uses CHECK (max_uses BETWEEN 1 AND 200 AND uses BETWEEN 0 AND max_uses)
);

CREATE INDEX idx_invite_links_school_class ON invite_links (school_class_id);
CREATE INDEX idx_invite_links_student ON invite_links (student_id);

-- Which stored link an account registered through: read once, when the account becomes active (email confirmed, or
-- straight away for Google). A deleted link leaves the account to the normal approval queue.
ALTER TABLE users ADD COLUMN invite_link_id BIGINT REFERENCES invite_links (id) ON DELETE SET NULL;

CREATE INDEX idx_users_invite_link ON users (invite_link_id);
