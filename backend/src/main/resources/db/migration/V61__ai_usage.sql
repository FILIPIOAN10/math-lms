-- One row per billed AI call, written the moment the provider answers - also when the answer is then refused (cut
-- off, "not a solution", bad JSON) or asked again, which the per-feature rows overwrite or never store. What the admin
-- reads as "this month's AI bill". No user, no content: only what was asked of which model and what it cost.
CREATE TABLE ai_usage (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feature       VARCHAR(20) NOT NULL,
    model         VARCHAR(80) NOT NULL,
    input_tokens  INT         NOT NULL DEFAULT 0,
    output_tokens INT         NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_ai_usage_created ON ai_usage (created_at);
