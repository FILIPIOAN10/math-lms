-- Editură → Carte → Teste: a publisher's books (a "Culegere EN 2026"...), each holding the tests taken from it.
-- Like the publishers, none ships with the app. Deleting a publisher deletes its books (they mean nothing without it);
-- deleting a book never deletes a test: the test stays, without a book (and keeps its publisher).
CREATE TABLE publisher_books (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publisher_id BIGINT        NOT NULL REFERENCES publishers (id) ON DELETE CASCADE,
    title        VARCHAR(200)  NOT NULL,
    description  VARCHAR(1000),
    created_at   TIMESTAMPTZ   NOT NULL,
    updated_at   TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_publisher_books_title CHECK (btrim(title) <> '')
);

-- One "Culegere EN 2026" per publisher, whatever its case (another publisher may have one of the same name).
CREATE UNIQUE INDEX uq_publisher_books_title ON publisher_books (publisher_id, lower(title));

ALTER TABLE quizzes ADD COLUMN book_id BIGINT REFERENCES publisher_books (id) ON DELETE SET NULL;
CREATE INDEX idx_quizzes_book ON quizzes (book_id);
