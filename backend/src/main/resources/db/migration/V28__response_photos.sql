-- S2: an open answer can have several photos (a solution often runs over 2-3 pages), at most 5, in the order taken.
-- Deleting the answer deletes its photo rows; the files are removed by the application.
CREATE TABLE response_photos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    response_id BIGINT      NOT NULL REFERENCES item_responses (id) ON DELETE CASCADE,
    image_key   TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_response_photos_response ON response_photos (response_id, id);

-- Every existing single photo becomes the first (only) photo of its answer.
INSERT INTO response_photos (response_id, image_key, created_at)
SELECT r.id, r.image_key, COALESCE(a.submitted_at, a.started_at)
FROM item_responses r
JOIN quiz_attempts a ON a.id = r.attempt_id
WHERE r.image_key IS NOT NULL;

-- Expand-contract: item_responses.image_key is no longer read or written from here on, but stays so that rolling back to
-- v0.3.0 still finds the photos taken before this migration. Drop it in a later migration, once v0.4.0 is in production.
COMMENT ON COLUMN item_responses.image_key IS 'Frozen since V28 (photos live in response_photos); drop after v0.4.0.';
