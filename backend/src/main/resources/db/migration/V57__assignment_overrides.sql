-- One student's exception to a homework (Canvas "Assign To" / Google Classroom "Excused"): their own deadline, or
-- excused (the homework does not count for them). The class deadline stays the default for everyone else. At most one
-- row per student and homework; a row that neither moves the deadline nor excuses means nothing, so it cannot exist.
CREATE TABLE assignment_overrides (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT      NOT NULL REFERENCES assignments (id) ON DELETE CASCADE,
    student_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    due_at        TIMESTAMPTZ,
    excused       BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_assignment_overrides_assignment_student UNIQUE (assignment_id, student_id),
    CONSTRAINT ck_assignment_overrides_meaningful CHECK (excused OR due_at IS NOT NULL)
);

-- A student's homework list loads their overrides by student (the unique index covers lookups by assignment).
CREATE INDEX idx_assignment_overrides_student ON assignment_overrides (student_id);
