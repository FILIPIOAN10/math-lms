-- AI barem + AI grade proposals (user's decisions 2026-10-26: Gemini only, the strongest model; the AI proposes, the
-- teacher confirms - nothing becomes a grade without a teacher's click).
--
-- 1. A teacher photographs the official barem of a test; the AI reads it and maps it onto the test's questions (the
--    right letter of each grilă, the barem of each Subiectul III requirement). The teacher reviews before it is saved.
--    Read in the background like ai_imports (QUEUED -> RUNNING -> DONE | FAILED): the strong model can think for longer
--    than a proxied request may last.
CREATE TABLE ai_barem_reads (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id       BIGINT       NOT NULL REFERENCES quizzes (id) ON DELETE CASCADE,
    teacher_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status        VARCHAR(10)  NOT NULL,
    page_count    INT          NOT NULL,
    -- The stored barem photos (JSON array of {key, type}); emptied once read, so they are not kept.
    page_keys     TEXT         NOT NULL,
    -- What the AI read: a JSON array of {label, correctLetter, barem, parts[{label, barem}], warnings}.
    result_json   TEXT,
    error         VARCHAR(500),
    model         VARCHAR(80),
    input_tokens  INT,
    output_tokens INT,
    created_at    TIMESTAMPTZ  NOT NULL,
    started_at    TIMESTAMPTZ,
    finished_at   TIMESTAMPTZ,
    CONSTRAINT ck_ai_barem_reads_status CHECK (status IN ('QUEUED', 'RUNNING', 'DONE', 'FAILED')),
    CONSTRAINT ck_ai_barem_reads_pages CHECK (page_count BETWEEN 1 AND 10)
);

CREATE INDEX idx_ai_barem_reads_status ON ai_barem_reads (status, id);
CREATE INDEX idx_ai_barem_reads_teacher ON ai_barem_reads (teacher_id, created_at DESC);

-- 2. For every open answer with photos and a barem, handed in while the feature is on, the AI proposes points per
--    requirement with a short reason. Only the photos, the statement and the barem are sent - no name, no account.
CREATE TABLE ai_grade_proposals (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id    BIGINT       NOT NULL REFERENCES quiz_attempts (id) ON DELETE CASCADE,
    item_id       BIGINT       NOT NULL REFERENCES quiz_items (id) ON DELETE CASCADE,
    status        VARCHAR(10)  NOT NULL,
    -- The proposal: points for the whole answer, and per requirement a JSON array of {partId, points, reason}.
    points        INT,
    parts_json    TEXT,
    reason        VARCHAR(2000),
    confidence    VARCHAR(10),
    error         VARCHAR(500),
    model         VARCHAR(80),
    input_tokens  INT,
    output_tokens INT,
    attempts      INT          NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL,
    started_at    TIMESTAMPTZ,
    finished_at   TIMESTAMPTZ,
    CONSTRAINT uq_ai_grade_proposals UNIQUE (attempt_id, item_id),
    CONSTRAINT ck_ai_grade_proposals_status CHECK (status IN ('QUEUED', 'RUNNING', 'DONE', 'FAILED')),
    CONSTRAINT ck_ai_grade_proposals_confidence CHECK (confidence IS NULL OR confidence IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT ck_ai_grade_proposals_points CHECK (points IS NULL OR points >= 0)
);

-- The worker takes the oldest QUEUED row; the daily limit counts the answers started since midnight.
CREATE INDEX idx_ai_grade_proposals_status ON ai_grade_proposals (status, id);
CREATE INDEX idx_ai_grade_proposals_started ON ai_grade_proposals (started_at);
