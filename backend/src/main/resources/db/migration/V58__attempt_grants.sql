-- Extra graded attempts for one student at one test (Moodle's user override): the test's own limit stays the same for
-- everyone else. One row per test and student, its count grows with each "+1 încercare"; capped so a slip of the
-- finger cannot open a test for good.
CREATE TABLE attempt_grants (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id    BIGINT      NOT NULL REFERENCES quizzes (id) ON DELETE CASCADE,
    student_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    extra      INTEGER     NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_attempt_grants_quiz_student UNIQUE (quiz_id, student_id),
    CONSTRAINT ck_attempt_grants_extra CHECK (extra BETWEEN 1 AND 10)
);

-- A student's quiz list loads all their grants at once.
CREATE INDEX idx_attempt_grants_student ON attempt_grants (student_id);
