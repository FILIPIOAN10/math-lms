-- EN structure: a Subiectul III problem has requirements a), b) (c)...) with their own points ("(2p) a) Arată că...",
-- "(3p) b) Calculează...") and their own barem, graded separately. One shared statement and figure, one set of photos
-- (the student hands in the whole solution); the item's points are the sum of its parts.
CREATE TABLE quiz_item_parts (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id   BIGINT  NOT NULL REFERENCES quiz_items (id) ON DELETE CASCADE,
    position  INT     NOT NULL,
    statement TEXT    NOT NULL,
    points    INT     NOT NULL CHECK (points >= 0),
    solution  TEXT,
    CONSTRAINT uk_quiz_item_parts_item_position UNIQUE (item_id, position)
);

-- The teacher's points for each part of one answer; the answer's awarded_points is their sum once every part has some.
CREATE TABLE response_part_points (
    response_id BIGINT NOT NULL REFERENCES item_responses (id) ON DELETE CASCADE,
    part_id     BIGINT NOT NULL REFERENCES quiz_item_parts (id) ON DELETE CASCADE,
    points      INT    NOT NULL CHECK (points >= 0),
    PRIMARY KEY (response_id, part_id)
);
