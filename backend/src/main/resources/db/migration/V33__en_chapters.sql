-- EN chapter pages: what a student opens after getting an EN question wrong. Each chapter is one page the teacher fills
-- with photos of the theory and a few worked examples. Not tied to a class or a book: the EN covers grades V-VIII, so
-- every student may read every page. The 20 chapters below come from docs/EN-capitole.md (official EN 2023-2026 papers);
-- the teacher may rename, reorder, add or remove them.
CREATE TABLE en_chapters (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(10)  NOT NULL,
    title    VARCHAR(200) NOT NULL,
    area     VARCHAR(10)  NOT NULL CHECK (area IN ('ALGEBRA', 'GEOMETRY')),
    position INT          NOT NULL,
    -- Optional text above the photos ("Ce trebuie să știi"), LaTeX allowed.
    notes    TEXT,
    CONSTRAINT uk_en_chapters_code UNIQUE (code)
);

-- The theory, photographed page by page, in upload order.
CREATE TABLE en_chapter_photos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id BIGINT       NOT NULL REFERENCES en_chapters (id) ON DELETE CASCADE,
    position   INT          NOT NULL,
    image_key  VARCHAR(200) NOT NULL
);

CREATE INDEX idx_en_chapter_photos_chapter ON en_chapter_photos (chapter_id, position);

-- Worked examples: a statement, its explained solution (LaTeX) and an optional figure.
CREATE TABLE en_chapter_examples (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id BIGINT       NOT NULL REFERENCES en_chapters (id) ON DELETE CASCADE,
    position   INT          NOT NULL,
    statement  TEXT         NOT NULL,
    solution   TEXT         NOT NULL,
    image_key  VARCHAR(200)
);

CREATE INDEX idx_en_chapter_examples_chapter ON en_chapter_examples (chapter_id, position);

