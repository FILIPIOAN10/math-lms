-- Feature 1 (grading without lost work): each teacher's bank of reusable comments ("Atenție la semn.", "Lipsește
-- unitatea de măsură."). Saved on purpose, never learned from what was typed (a comment may name a student, and these
-- outlive a student's erasure). Most-used first, so the list follows the teacher's habits.
CREATE TABLE comment_snippets (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id   BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    text         VARCHAR(500) NOT NULL,
    use_count    INT          NOT NULL DEFAULT 0,
    last_used_at TIMESTAMPTZ,
    created_at   TIMESTAMPTZ  NOT NULL
);

-- "Atenție la semn" and "atenție la semn" are the same comment; the database is the last guard (two tabs saving at once).
CREATE UNIQUE INDEX uk_comment_snippets_teacher_text ON comment_snippets (teacher_id, lower(text));
CREATE INDEX idx_comment_snippets_teacher_use ON comment_snippets (teacher_id, use_count DESC);
