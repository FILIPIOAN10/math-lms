-- Tutor AI (the Python service in /tutor): the theory of the EN chapter pages (V33/V35), cut into chunks and
-- embedded, so the tutor can find the passages that explain an exercise.
-- The source of truth stays en_chapters / en_chapter_examples: this table is derived data and can be emptied and
-- rebuilt at any time. Written and read only by the tutor service; the Java backend never touches it.

CREATE EXTENSION IF NOT EXISTS vector;

-- What the vision model read from each theory photo uploaded on a chapter page (en_chapter_photos). Kept so the
-- paid transcription happens once per photo; the chunks below are built from this text and can be rebuilt freely.
CREATE TABLE tutor_photo_transcripts (
    photo_id         BIGINT       PRIMARY KEY REFERENCES en_chapter_photos (id) ON DELETE CASCADE,
    content          TEXT         NOT NULL,
    transcribed_with VARCHAR(60)  NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE tutor_chunks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id    BIGINT       NOT NULL REFERENCES en_chapters (id) ON DELETE CASCADE,
    -- Set when the chunk comes from a photo (deleting the photo drops its chunks); NULL for the chapter's own text.
    photo_id      BIGINT       REFERENCES en_chapter_photos (id) ON DELETE CASCADE,
    kind          VARCHAR(10)  NOT NULL CHECK (kind IN ('THEORY', 'EXAMPLE')),
    position      INT          NOT NULL,
    content       TEXT         NOT NULL,
    -- SHA-256 of the chunk text: re-running the ingestion updates in place instead of duplicating.
    content_hash  CHAR(64)     NOT NULL,
    -- Vectors from different embedding models are not comparable, so each row says which model made it.
    embedded_with VARCHAR(60)  NOT NULL,
    -- 1536 = text-embedding-3-small. Another model with another size needs a new migration and a re-index.
    embedding     vector(1536) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_tutor_chunks_chapter_hash UNIQUE (chapter_id, content_hash)
);

CREATE INDEX idx_tutor_chunks_chapter ON tutor_chunks (chapter_id);
CREATE INDEX idx_tutor_chunks_photo ON tutor_chunks (photo_id) WHERE photo_id IS NOT NULL;

-- Approximate nearest-neighbour search by cosine distance.
CREATE INDEX idx_tutor_chunks_embedding ON tutor_chunks USING hnsw (embedding vector_cosine_ops);
