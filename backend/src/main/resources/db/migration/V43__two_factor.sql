-- F8: two-step sign-in (TOTP, an authenticator app) for staff: required for ADMIN, optional for TEACHER.
-- totp_secret is encrypted by the app (AES-GCM, key derived from JWT_SECRET): a database dump alone gives no codes.
-- totp_last_step = the 30-second step of the last code accepted, so the same code can never be used twice.
ALTER TABLE users ADD COLUMN totp_secret     VARCHAR(255);
ALTER TABLE users ADD COLUMN totp_enabled_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN totp_last_step  BIGINT;

-- Ten single-use codes for a lost phone. Only a SHA-256 of each is stored (they are long random strings, shown once).
CREATE TABLE totp_recovery_codes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    code_hash  VARCHAR(64) NOT NULL,
    used_at    TIMESTAMPTZ
);

CREATE INDEX idx_totp_recovery_codes_user ON totp_recovery_codes (user_id);
