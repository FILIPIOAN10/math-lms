-- Faza 3 (AI/OCR import): a teacher photographs 1-5 textbook pages, an AI reads the questions on them, the teacher reviews
-- and turns them into a DRAFT quiz. Only textbook pages are ever sent (user's decision 2026-10-12): no student photos, no
-- personal data. One row per upload, worked through by a background worker (QUEUED -> RUNNING -> DONE | FAILED).
CREATE TABLE ai_imports (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id      BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- Where the quiz will go, as chosen at upload (both editable again at review).
    school_class_id BIGINT       REFERENCES school_classes (id) ON DELETE SET NULL,
    chapter_id      BIGINT       REFERENCES chapters (id) ON DELETE SET NULL,
    status          VARCHAR(10)  NOT NULL,
    page_count      INT          NOT NULL,
    -- The stored page files (a JSON array of {key, type}: name in the ai-pages folder, image type); emptied once the quiz is made or the pages
    -- expire, so no textbook photo is kept longer than needed.
    page_keys       TEXT         NOT NULL,
    -- What the AI read: a JSON array of questions (statement, type, options, points, section, figure flag, warnings).
    items_json      TEXT,
    error           VARCHAR(500),
    provider        VARCHAR(30),
    model           VARCHAR(80),
    input_tokens    INT,
    output_tokens   INT,
    attempts        INT          NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL,
    started_at      TIMESTAMPTZ,
    finished_at     TIMESTAMPTZ,
    quiz_id         BIGINT       REFERENCES quizzes (id) ON DELETE SET NULL,
    CONSTRAINT ck_ai_imports_status CHECK (status IN ('QUEUED', 'RUNNING', 'DONE', 'FAILED')),
    CONSTRAINT ck_ai_imports_pages CHECK (page_count BETWEEN 1 AND 20)
);

-- The worker takes the oldest QUEUED row; the daily page limit sums one teacher's uploads since midnight.
CREATE INDEX idx_ai_imports_status ON ai_imports (status, id);
CREATE INDEX idx_ai_imports_teacher ON ai_imports (teacher_id, created_at DESC);
