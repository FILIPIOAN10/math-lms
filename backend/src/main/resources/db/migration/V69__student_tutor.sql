-- The student's "Nu înțeleg…" box (an AI that explains from the EN lessons only and sends the student to the page).
--
-- tutor_daily_usage: how many questions a student asked on one day (Romanian calendar day). The limit is checked and
-- counted in one statement (INSERT .. ON CONFLICT .. WHERE questions < limit), so two tabs cannot both take the last
-- one. Only a count: what was asked is not kept here. Rows older than a week are dropped by the application.
--
-- tutor_unanswered_questions: the questions the lessons did not answer ("Nu am asta în manual."), so the teacher sees
-- what the class does not know. The text only, never the answer; the list shows no names; kept 30 days; an answered
-- question is not stored at all. Both tables go with the account on GDPR erasure (and cascade on a hard delete).
CREATE TABLE tutor_daily_usage (
    student_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    day        DATE   NOT NULL,
    questions  INT    NOT NULL DEFAULT 0 CHECK (questions >= 0),
    PRIMARY KEY (student_id, day)
);

CREATE TABLE tutor_unanswered_questions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    question   VARCHAR(500) NOT NULL,
    asked_at   TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_tutor_unanswered_student_asked ON tutor_unanswered_questions (student_id, asked_at DESC);
CREATE INDEX idx_tutor_unanswered_asked ON tutor_unanswered_questions (asked_at);
